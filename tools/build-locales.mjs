import { lstat, readFile, realpath, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { contentRoot } from './content-root.mjs';

export async function writeLocaleBundle() {
  const root = await realpath(fileURLToPath(new URL('../', import.meta.url)));
  const publicRoot = await contentRoot(root, 'public');
  const catalogs = {};
  for (const language of ['en', 'zh-Hant', 'zh-Hans']) {
    catalogs[language] = JSON.parse(await readFile(path.join(root, 'locales', language + '.json'), 'utf8'));
  }
  const sourceKeys = Object.keys(catalogs['zh-Hant']).sort();
  const tokens = text => JSON.stringify((text.match(/\{[a-z]+\}/g) || []).sort());
  for (const [language, messages] of Object.entries(catalogs)) {
    if (JSON.stringify(Object.keys(messages).sort()) !== JSON.stringify(sourceKeys)) throw new Error(`Incomplete catalog: ${language}`);
    for (const source of sourceKeys) {
      if (typeof messages[source] !== 'string' || !messages[source].trim() || tokens(source) !== tokens(messages[source])) throw new Error(`Invalid message: ${language}: ${source}`);
    }
  }
  const destination = path.join(publicRoot, 'locales.js');
  try { if ((await lstat(destination)).isSymbolicLink()) throw new Error('Locale output must not be a link'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const bundle = '// Generated by tools/build-locales.mjs. Edit locales/*.json.\n' +
    'globalThis.AutoKeyMessages = ' + JSON.stringify(catalogs, null, 2) + ';\n';
  await writeFile(destination, bundle, 'utf8');
  console.log(`Bundled ${sourceKeys.length} messages in 3 languages`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await writeLocaleBundle();
